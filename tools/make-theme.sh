#!/bin/bash
#
# Generate a complete pfx theme from a palette.
#
# Usage: tools/make-theme.sh <name> <palette-file>
#
# Every themed app reads one file out of the theme directory, so a theme is
# "complete" only when all of them exist — a missing file means that app
# silently falls back to its own unstyled defaults, which looks broken in a
# way that's hard to diagnose. Generating them from a single palette is how
# they stay in sync.
#
# The palette file defines: base surface text muted accent urgent warning border
# and the sixteen ANSI colours ansi0..ansi15. All values are #rrggbb.

set -eEuo pipefail

name="${1:?usage: make-theme.sh <name> <palette-file>}"
palette="${2:?usage: make-theme.sh <name> <palette-file>}"

# shellcheck source=/dev/null
source "$palette"

root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
out="$root/themes/$name"

rm -rf "$out"
mkdir -p "$out/backgrounds"

# --- Alacritty -------------------------------------------------------------
cat >"$out/alacritty.toml" <<EOF
# $name — generated by tools/make-theme.sh. Do not edit; edit the palette.

[colors.primary]
background = "$base"
foreground = "$text"

[colors.cursor]
text = "$base"
cursor = "$accent"

[colors.selection]
text = "$text"
background = "$surface"

[colors.normal]
black   = "$ansi0"
red     = "$ansi1"
green   = "$ansi2"
yellow  = "$ansi3"
blue    = "$ansi4"
magenta = "$ansi5"
cyan    = "$ansi6"
white   = "$ansi7"

[colors.bright]
black   = "$ansi8"
red     = "$ansi9"
green   = "$ansi10"
yellow  = "$ansi11"
blue    = "$ansi12"
magenta = "$ansi13"
cyan    = "$ansi14"
white   = "$ansi15"
EOF

# --- Waybar (GTK CSS named colours) ---------------------------------------
cat >"$out/waybar.css" <<EOF
/* $name — generated by tools/make-theme.sh. Do not edit; edit the palette. */
@define-color base    $base;
@define-color surface $surface;
@define-color text    $text;
@define-color muted   $muted;
@define-color accent  $accent;
@define-color urgent  $urgent;
@define-color warning $warning;
@define-color border  $border;
EOF

# Walker uses the same GTK named-colour mechanism.
cp "$out/waybar.css" "$out/walker.css"

# --- Mako ------------------------------------------------------------------
cat >"$out/mako.ini" <<EOF
# $name — generated by tools/make-theme.sh. Do not edit; edit the palette.
background-color=${base}f2
text-color=$text
border-color=$border
progress-color=over $surface

[urgency=low]
border-color=$muted

[urgency=high]
border-color=$urgent
text-color=$text
EOF

# --- Hyprland (border colours only) ---------------------------------------
cat >"$out/hyprland.conf" <<EOF
# $name — generated by tools/make-theme.sh. Do not edit; edit the palette.
general {
    col.active_border = rgb(${accent#\#})
    col.inactive_border = rgb(${border#\#})
}

decoration {
    shadow {
        color = rgba(${base#\#}99)
    }
}
EOF

# --- Hyprlock --------------------------------------------------------------
cat >"$out/hyprlock.conf" <<EOF
# $name — generated by tools/make-theme.sh. Do not edit; edit the palette.
\$base = rgb(${base#\#})
\$text = rgb(${text#\#})
\$accent = rgb(${accent#\#})
\$urgent = rgb(${urgent#\#})
EOF

# --- btop ------------------------------------------------------------------
cat >"$out/btop.theme" <<EOF
# $name — generated by tools/make-theme.sh. Do not edit; edit the palette.
theme[main_bg]="$base"
theme[main_fg]="$text"
theme[title]="$text"
theme[hi_fg]="$accent"
theme[selected_bg]="$surface"
theme[selected_fg]="$accent"
theme[inactive_fg]="$muted"
theme[graph_text]="$muted"
theme[proc_misc]="$accent"
theme[cpu_box]="$border"
theme[mem_box]="$border"
theme[net_box]="$border"
theme[proc_box]="$border"
theme[div_line]="$border"
theme[temp_start]="$ansi2"
theme[temp_mid]="$warning"
theme[temp_end]="$urgent"
theme[cpu_start]="$ansi2"
theme[cpu_mid]="$warning"
theme[cpu_end]="$urgent"
theme[free_start]="$ansi4"
theme[free_mid]="$accent"
theme[free_end]="$ansi6"
theme[cached_start]="$ansi5"
theme[cached_mid]="$accent"
theme[cached_end]="$ansi6"
theme[available_start]="$warning"
theme[available_mid]="$accent"
theme[available_end]="$ansi2"
theme[used_start]="$ansi2"
theme[used_mid]="$warning"
theme[used_end]="$urgent"
theme[download_start]="$ansi4"
theme[download_mid]="$accent"
theme[download_end]="$ansi6"
theme[upload_start]="$ansi5"
theme[upload_mid]="$accent"
theme[upload_end]="$urgent"
EOF

# --- Wallpapers ------------------------------------------------------------
# Generated rather than downloaded so the repo carries no third-party image
# licensing, and so every theme is guaranteed to have a matching background.
# JPEG, not PNG: a 4K PNG of a smooth gradient is ~20 MB and would put a
# hundred megabytes of wallpaper in the repo for no visible gain.
magick -size 3840x2160 \
  "gradient:${base}-${surface}" \
  -attenuate 0.35 +noise Gaussian \
  -blur 0x2 \
  -quality 90 \
  "$out/backgrounds/01-gradient.jpg"

# The bloom layer is blended at low opacity rather than drawn directly — at
# full strength the accent colour blows out and stops reading as a background.
magick -size 3840x2160 "xc:$base" \
  \( -size 3840x2160 "xc:$base" \
  -fill "$accent" -draw "circle 3100,420 3100,1080" \
  -fill "$surface" -draw "circle 600,1980 600,2600" \
  -blur 0x300 \) \
  -compose blend -define compose:args=38 -composite \
  -quality 90 \
  "$out/backgrounds/02-bloom.jpg"

echo "Generated theme '$name' ($(find "$out" -type f | wc -l) files)"
